import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { MIGRATIONS_DIR, createMigratedDb } from "@/lib/db/local-db";
import { buildSeed } from "@/lib/db/seed-data";
import { seedDatabase } from "@/lib/db/seed-runner";

// Render the demo dataset as plain SQL for the ephemeral preview D1 database
// (applied by the deploy-preview workflow via `wrangler d1 execute`). Uses a
// real migrated sqlite database as the single source, then dumps every table so
// the SQL cannot drift from the schema.

const TABLES = [
  "studios",
  "studio_settings",
  "members",
  "class_types",
  "class_sessions",
  "bookings",
  "invoices",
  "invoice_line_items",
  "notification_outbox",
] as const;

function sqlValue(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number" || typeof value === "bigint") return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
}

const { db, sqlite } = createMigratedDb(":memory:");
await seedDatabase(db, buildSeed());

const lines: string[] = [
  "-- Studiobook demo seed for the ephemeral preview D1 database.",
  "-- Generated by scripts/emit-seed-sql.ts — run `pnpm db:emit-seed-sql` to refresh.",
  "PRAGMA foreign_keys=OFF;",
  "",
];

for (const table of TABLES) {
  const columns = (sqlite.prepare(`PRAGMA table_info("${table}")`).all() as { name: string }[]).map(
    (column) => column.name,
  );
  const rows = sqlite.prepare(`SELECT * FROM "${table}"`).all() as Record<string, unknown>[];
  for (const row of rows) {
    const columnList = columns.map((column) => `"${column}"`).join(", ");
    const valueList = columns.map((column) => sqlValue(row[column])).join(", ");
    lines.push(`INSERT INTO "${table}" (${columnList}) VALUES (${valueList});`);
  }
  lines.push("");
}
lines.push("PRAGMA foreign_keys=ON;");

const outPath = resolve(MIGRATIONS_DIR, "seed.sql");
writeFileSync(outPath, `${lines.join("\n")}\n`);
console.log(`Studiobook: wrote ${outPath} (${lines.length} lines)`);
